  pw.Widget _transactionsTable({

    required List<TransactionModel> transactions,

    required String currencySymbol,

    required bool modern,

    required Map<String, String> categoryMap,

    required Map<String, String> accountMap,

  }) {

    return pw.Table(

      border: pw.TableBorder.all(

        color: PdfColors.grey300,

        width: 0.5,

      ),

      columnWidths: {

        0: const pw.FixedColumnWidth(56),

        1: const pw.FixedColumnWidth(94),

        2: const pw.FixedColumnWidth(78),

        3: const pw.FixedColumnWidth(58),

        4: const pw.FixedColumnWidth(108),

        5: const pw.FlexColumnWidth(),

      },

      children: [

        pw.TableRow(

          repeat: true,

          decoration: pw.BoxDecoration(

            color: modern

                ? PdfColor.fromHex('#1565C0')

                : PdfColors.grey300,

          ),

          children: [

            _tableHeader(

              'Date',

              modern: modern,

            ),

            _tableHeader(

              'Type',

              modern: modern,

            ),

            _tableHeader(

              'Amount',

              modern: modern,

            ),

            _tableHeader(

              'Category',

              modern: modern,

            ),

            _tableHeader(

              'Account',

              modern: modern,

            ),

            _tableHeader(

              'Details',

              modern: modern,

            ),

          ],

        ),

        ...transactions.map(

          (t) {

            final amount =

                t.amount / 100;

            final categoryId =

                t.categoryId;

            final categoryName =

                categoryId == null ||

                        categoryId.isEmpty

                    ? '—'

                    : categoryMap[categoryId] ??

                        'Unknown Category';

            final accountName =

                accountMap[t.accountId] ??

                    'Unknown Account';

            final toAccountId =

                t.toAccountId;

            final toAccountName =

                toAccountId == null ||

                        toAccountId.isEmpty

                    ? null

                    : accountMap[toAccountId] ??

                        'Unknown Account';

            final displayAccount =

                t.type == 'transfer' &&

                        toAccountName != null

                    ? '$accountName to $toAccountName'

                    : accountName;

            return pw.TableRow(

              decoration: modern

                  ? pw.BoxDecoration(

                      color: _rowColorForType(

                        t.type,

                      ),

                    )

                  : null,

              children: [

                _tableCell(

                  _formatDate(

                    t.transactionDate,

                  ),

                ),

                _tableCell(

                  _typeLabel(

                    t.type,

                  ),

                ),

                _tableCell(

                  _formatAmount(

                    type: t.type,

                    amount: amount,

                    currencySymbol:

                        currencySymbol,

                  ),

                ),

                _tableCell(

                  categoryName,

                ),

                _tableCell(

                  displayAccount,

                ),

                _tableCell(

                  _transactionDetails(

                    transaction: t,

                  ),

                ),

              ],

            );

          },

        ),

      ],

    );

  }

  String _typeLabel(

    String type,

  ) {

    switch (type) {

      case 'income':

        return 'Income';

      case 'expense':

        return 'Expense';

      case 'transfer':

        return 'Transfer';

      case 'borrowed':

        return 'Borrowed';

      case 'lent':

        return 'Lent';

      case 'repaymentPaid':

        return 'Repayment Paid';

      case 'repaymentReceived':

        return 'Repayment Received';

      default:

        return type;

    }

  }

  String _formatAmount({

    required String type,

    required double amount,

    required String currencySymbol,

  }) {

    String prefix;

    switch (type) {

      case 'income':

      case 'borrowed':

      case 'repaymentReceived':

        prefix = '+';

        break;

      case 'expense':

      case 'lent':

      case 'repaymentPaid':

        prefix = '-';

        break;

      default:

        prefix = '';

        break;

    }

    return '$prefix$currencySymbol${_formatNumber(amount)}';

  }

  String _formatNumber(

    num value,

  ) {

    final rounded = value.round();

    final isNegative = rounded < 0;

    final digits = rounded.abs().toString();

    final buffer = StringBuffer();

    for (var i = 0; i < digits.length; i++) {

      if (i > 0 &&

          (digits.length - i) % 3 == 0) {

        buffer.write(',');

      }

      buffer.write(digits[i]);

    }

    return isNegative

        ? '-${buffer.toString()}'

        : buffer.toString();

  }

  PdfColor _rowColorForType(

    String type,

  ) {

    switch (type) {

      case 'income':

      case 'borrowed':

      case 'repaymentReceived':

        return PdfColors.green50;

      case 'expense':

      case 'lent':

      case 'repaymentPaid':

        return PdfColors.red50;

      case 'transfer':

        return PdfColors.blue50;

      default:

        return PdfColors.grey100;

    }

  }

  String _transactionDetails({

    required TransactionModel transaction,

  }) {

    final parts = <String>[];

    final counterparty =

        transaction.counterpartyName?.trim();

    switch (transaction.type) {

      case 'borrowed':

        if (counterparty != null &&

            counterparty.isNotEmpty) {

          parts.add(

            'From: $counterparty',

          );

        }

        break;

      case 'lent':

        if (counterparty != null &&

            counterparty.isNotEmpty) {

          parts.add(

            'To: $counterparty',

          );

        }

        break;

      case 'repaymentPaid':

        if (counterparty != null &&

            counterparty.isNotEmpty) {

          parts.add(

            'Paid to: $counterparty',

          );

        }

        break;

      case 'repaymentReceived':

        if (counterparty != null &&

            counterparty.isNotEmpty) {

          parts.add(

            'Received from: $counterparty',

          );

        }

        break;

    }

    final dueDate =

        transaction.dueDate;

    if (dueDate != null) {

      parts.add(

        'Due: ${_formatDate(dueDate)}',

      );

    }

    final notes =

        transaction.notes?.trim();

    if (notes != null &&

        notes.isNotEmpty) {

      parts.add(notes);

    }

    return parts.join(' • ');

  }

  String _formatDate(

    DateTime date,

  ) {

    final day =

        date.day.toString().padLeft(2, '0');

    final month =

        date.month.toString().padLeft(2, '0');

    final year =

        (date.year % 100)

            .toString()

            .padLeft(2, '0');

    return '$day/$month/$year';

  }

