  final Isar isar;

  PdfExportService(this.isar);

  Future<File>

      generateMonthlyReport({

    required String

        reportTitle,

    required String

        reportPeriod,

    required String

        currencySymbol,

    required List<

            TransactionModel>

        transactions,

    required double income,

    required double expense,

    required double balance,

    required ExportReportStyle

        style,

  })

  async {

    final categories =

        await isar.categoryModels

            .where()

            .findAll();

    final accounts =

        await isar.accountModels

            .where()

            .findAll();

    final categoryMap = <String, String>{

      for (final category in categories)

        category.uuid: category.name,

    };

    final accountMap = <String, String>{

      for (final account in accounts)

        account.uuid: account.name,

    };

    // =====================================================

    // LOAD FONTS

    // =====================================================

    final regularFont =

        pw.Font.ttf(

      await rootBundle.load(

        'assets/fonts/NotoSans-Regular.ttf',

      ),

    );

    final boldFont =

        pw.Font.ttf(

      await rootBundle.load(

        'assets/fonts/NotoSans-Bold.ttf',

      ),

    );

    // =====================================================

    // PDF DOCUMENT

    // =====================================================

    final pdf =

        pw.Document(

      theme: pw.ThemeData.withFont(

        base: regularFont,

        bold: boldFont,

      ),

    );

    final generatedDate =

        DateTime.now().toUtc();

    final savingsRate =

        income <= 0

            ? 0

            : ((balance / income) *

                    100)

                .clamp(

              0,

              100,

            );

    // =====================================================

    // ADD PAGE

    // =====================================================

    pdf.addPage(

      pw.MultiPage(

        pageFormat:

            PdfPageFormat.a4,

        margin:

            const pw.EdgeInsets.all(

          32,

        ),

        // =================================================

        // FOOTER

        // =================================================

        footer:

            (context) {

          return pw.Container(

            margin:

                const pw.EdgeInsets.only(

              top: 16,

            ),

            child: pw.Row(

              mainAxisAlignment:

                  pw.MainAxisAlignment

                      .spaceBetween,

              children: [

                pw.Text(

                  'Generated on '

                  '${generatedDate.day}/'

                  '${generatedDate.month}/'

                  '${generatedDate.year}',

                  style:

                      const pw.TextStyle(

                    fontSize: 10,

                    color:

                        PdfColors.grey,

                  ),

                ),

                pw.Text(

                  'Generated by '

                  '${AppConstants.appCompanyName}',

                  style:

                      const pw.TextStyle(

                    fontSize: 10,

                    color:

                        PdfColors.grey,

                  ),

                ),

              ],

            ),

          );

        },

        // =================================================

        // PAGE CONTENT

        // =================================================

        build: (context) {

          if (

            style ==

            ExportReportStyle

                .classic

          ) {

            return _buildClassicReport(

              reportTitle: reportTitle,

              reportPeriod: reportPeriod,

              currencySymbol: currencySymbol,

              transactions: transactions,

              income: income,

              expense: expense,

              balance: balance,

              categoryMap: categoryMap,

              accountMap: accountMap,

            );

          }

          return _buildModernReport(

            reportTitle: reportTitle,

            reportPeriod: reportPeriod,

            currencySymbol: currencySymbol,

            transactions: transactions,

            income: income,

            expense: expense,

            balance: balance,

            savingsRate: savingsRate.toDouble(),

            categoryMap: categoryMap,

            accountMap: accountMap,

          );

        },

      ),

    );

    // =====================================================

    // SAVE FILE

    // =====================================================

    final dir =

        await getTemporaryDirectory();

    final file = File(

      '${dir.path}/finance_report.pdf',

    );

    await file.writeAsBytes(

      await pdf.save(),

    );

    return file;

  }

